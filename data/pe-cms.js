window.PE_CMS.PLACEHOLDER_IMG = '../assets/images/identity_main-isologo.svg';
window.PE_CMS.setImage = function (img, url, alt) {
  if (!img) return;
  img.removeAttribute('srcset');
  img.alt = alt || '';
  if (url) { img.src = url; img.classList.remove('pe-img-placeholder'); }
  else { img.src = window.PE_CMS.PLACEHOLDER_IMG; img.classList.add('pe-img-placeholder'); }
};

/* Lookup helpers shared by the pages */
window.PE_CMS.find = function (coleccion, slug) {
  var list = window.PE_CMS[coleccion] || [];
  for (var i = 0; i < list.length; i++) if (list[i].slug === slug) return list[i];
  return null;
};
